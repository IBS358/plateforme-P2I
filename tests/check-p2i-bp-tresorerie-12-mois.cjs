/** P2I — Vérification du moteur de trésorerie à 12 mois. */
"use strict";
const fs=require("node:fs"),vm=require("node:vm"),path=require("node:path"),assert=require("node:assert/strict");
const context=vm.createContext({});
vm.runInContext(fs.readFileSync(path.resolve(__dirname,"../js/p2i-bp-decouverte-tresorerie-12-mois.js"),"utf8"),context);
const engine=context.P2I_BP_MOTEUR_TRESORERIE;
const make=()=>Object.fromEntries(engine.champs_requis.map(k=>[k,0]));
const inputs=Array.from({length:12},()=>({...make(),ventes_clients:10000,achats_matiere:4000,salaires:2000,charges_exploitation:1000,service_dette:500}));
const result=engine.calculer({solde_initial:5000,mois:inputs});
assert.equal(result.valide,true,JSON.stringify(result.erreurs));
assert.equal(result.tresorerie_mensuelle.length,12);
assert.equal(result.tresorerie_mensuelle[0].encaissements,10000);
assert.equal(result.tresorerie_mensuelle[0].decaissements,7500);
assert.equal(result.tresorerie_mensuelle[0].solde_final,7500);
assert.equal(result.tresorerie_mensuelle[1].solde_initial,7500);
assert.equal(result.solde_final,35000);
assert.equal(engine.calculer({solde_initial:5000,mois:inputs.slice(0,11)}).valide,false);
assert.equal(engine.calculer({solde_initial:null,mois:inputs}).valide,false);
const missing=inputs.map(x=>({...x}));delete missing[2].salaires;
const incomplete=engine.calculer({solde_initial:5000,mois:missing});
assert.equal(incomplete.valide,false);
assert.equal(incomplete.tresorerie_mensuelle,null);
assert.ok(incomplete.erreurs.some(e=>e.includes("Mois 3")&&e.includes("salaires")));
const negative=inputs.map(x=>({...x}));negative[0].achats_matiere=-10;
assert.equal(engine.calculer({solde_initial:5000,mois:negative}).valide,false);
const deficit=inputs.map(x=>({...x}));deficit[0].investissements=15000;
const deficitResult=engine.calculer({solde_initial:5000,mois:deficit});
assert.equal(deficitResult.valide,true);
assert.equal(deficitResult.tresorerie_mensuelle[0].solde_final,-7500);
console.log("Moteur trésorerie : 12 mois, reports, champs manquants et déficits contrôlés.");
