const { chromium } = require('playwright');
const path = require('path');
(async () => {
  const browser = await chromium.launch({headless:true});
  const page = await browser.newPage();
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const url = 'file://' + path.resolve('business-plan-decouverte.html');
  await page.goto(url,{waitUntil:'domcontentloaded',timeout:90000});
  const selector=page.locator('#up-choice');
  await selector.waitFor({timeout:30000});
  const options=await selector.locator('option').evaluateAll(nodes=>nodes.map(n=>({value:n.value,text:n.textContent.trim()})));
  console.log('Nombre d\'options:',options.length);
  const mobilier=options.find(x=>/mobilier métallique professionnel/i.test(x.text));
  if(!mobilier)throw new Error('UP mobilier absente du sélecteur sur cette branche; importer le BP complet avant validation.');
  await selector.selectOption(mobilier.value);
  await page.waitForTimeout(1500);
  const body=await page.locator('body').innerText();
  if(!/mobilier métallique professionnel/i.test(body))throw new Error('BP mobilier non visible après sélection.');
  if(errors.length)throw new Error('Erreurs JavaScript: '+errors.join(' | '));
  console.log('Sélection mobilier : OK');
  await page.reload({waitUntil:'domcontentloaded',timeout:90000});
  await page.waitForTimeout(1500);
  const refreshed=await page.locator('body').innerText();
  if(!/mobilier métallique professionnel/i.test(refreshed))throw new Error('BP mobilier non visible après actualisation.');
  if(errors.length)throw new Error('Erreurs JavaScript: '+errors.join(' | '));
  console.log('Actualisation mobilier : OK');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
