const { chromium } = require('playwright');
const path = require('path');
(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const url = 'file://' + path.resolve('business-plan-decouverte.html');
  await page.goto(url, { waitUntil: 'domcontentloaded', timeout: 90000 });
  const selector = page.locator('#up-choice');
  await selector.waitFor({ timeout: 30000 });
  const options = await selector.locator('option').evaluateAll(nodes => nodes.map(n => ({value:n.value,text:n.textContent.trim()})));
  const mobilier = options.find(x => /mobilier métallique professionnel/i.test(x.text));
  const outillage = options.find(x => /outillage manuel/i.test(x.text));
  if (!mobilier) throw new Error('UP mobilier absente du fichier de cette branche : intégrer le BP complet avant validation.');
  if (!outillage) throw new Error('UP témoin Outillage manuel absente.');
  if (options.filter(x => x.value).length < 96) throw new Error('Sélecteur incomplet : moins de 96 UP.');
  const check = async (expected) => {
    const text = await page.locator('body').innerText();
    if (!text.includes(expected)) throw new Error('BP non visible : ' + expected);
    if (errors.length) throw new Error('Erreur JavaScript : ' + errors.join(' | '));
    if (await page.locator('#app').isVisible() === false) throw new Error('Contenu BP masqué.');
  };
  await selector.selectOption(mobilier.value);
  await page.waitForTimeout(1200);
  await check('mobilier métallique');
  await page.reload({ waitUntil: 'domcontentloaded', timeout: 90000 });
  await page.waitForTimeout(1200);
  await check('mobilier métallique');
  await page.locator('#up-choice').selectOption(outillage.value);
  await page.waitForTimeout(1200);
  await check('Outillage manuel');
  await page.locator('#up-choice').selectOption(mobilier.value);
  await page.waitForTimeout(1200);
  await check('mobilier métallique');
  console.log('PASS: 96 UP, sélection mobilier, actualisation, Outillage, retour mobilier, aucune erreur JS.');
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
